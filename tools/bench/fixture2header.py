#!/usr/bin/env python3
"""Host replay fixtures as a C header, for the on-device replay test (step 7b).

test/test_shipped_profile replays the same captures as the host suite (test/test_replay_corpus) on
the ESP32, so the board's float Goertzel and the shipped gates see the input the host asserts on.
The board has no file system in the test build: the PCM goes into flash as const arrays.

Reads what src/host/Replay.cpp reads: a RAW transcript (.csv, the pcm column, RAW_BEGIN sr=,
RAW_SUMMARY baseline= when present) or a .wav (first channel; 16-bit scaled to the 24-bit range,
as loadWav does). Each input becomes `const int32_t k<Name>Pcm[]`, plus its length, rate and baseline.

  python tools/bench/fixture2header.py --out test/test_shipped_profile/fixtures.h \
      Chirp=test/fixtures/chirp3200_90cm_2026-10-16.csv \
      Tone3300=test/fixtures/tone3300_90cm_2026-10-16.csv \
      Hop=test/fixtures/hop5_25x5g10_70cm_2026-10-16.csv \
      Speech=test/fixtures/radio_speech_110cm_2026-10-16.wav
"""
import argparse
import os
import re
import struct
import sys


def load_csv(path):
    pcm, rate, baseline, pcm_col = [], 16000, None, -1
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if line.startswith("RAW_BEGIN "):
                m = re.search(r" sr=(\d+)", line)
                if m:
                    rate = int(m.group(1))
            elif line.startswith("RAW_SUMMARY "):
                m = re.search(r" baseline=(-?[\d.]+)", line)
                if m:
                    baseline = float(m.group(1))
            elif line.startswith("ms,"):
                pcm_col = line.split(",").index("pcm")
            elif pcm_col >= 0 and line[:1].isdigit():
                cols = line.split(",")
                if len(cols) > pcm_col:
                    pcm.append(int(cols[pcm_col]))
    return pcm, rate, baseline


def load_wav(path):
    with open(path, "rb") as f:
        data = f.read()
    if data[:4] != b"RIFF" or data[8:12] != b"WAVE":
        sys.exit(f"{path}: not a WAV file")
    pos, channels, bits, rate = 12, 1, 16, 16000
    while pos + 8 <= len(data):
        tag, size = data[pos:pos + 4], struct.unpack_from("<I", data, pos + 4)[0]
        body = pos + 8
        if tag == b"fmt ":
            channels, rate = struct.unpack_from("<HI", data, body + 2)
            bits = struct.unpack_from("<H", data, body + 14)[0]
        elif tag == b"data":
            step = bits // 8 * channels
            pcm = []
            for i in range(size // step):
                s = body + i * step
                if bits == 16:
                    pcm.append(struct.unpack_from("<h", data, s)[0] << 8)
                elif bits == 24:
                    v = data[s] | data[s + 1] << 8 | data[s + 2] << 16
                    pcm.append(v - (1 << 24) if v & 0x800000 else v)
                elif bits == 32:
                    pcm.append(struct.unpack_from("<i", data, s)[0] >> 8)
            return pcm, rate, None
        pos = body + size + (size & 1)
    sys.exit(f"{path}: no data chunk")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("fixtures", nargs="+", help="Name=path")
    args = ap.parse_args()

    out = ["// Generated by tools/bench/fixture2header.py from test/fixtures; do not edit.", "#pragma once", "",
           "#include <stddef.h>", "#include <stdint.h>", ""]
    for spec in args.fixtures:
        name, _, path = spec.partition("=")
        pcm, rate, baseline = load_wav(path) if path.endswith(".wav") else load_csv(path)
        if not pcm:
            sys.exit(f"{path}: no samples")
        out.append(f"// {os.path.basename(path)}: {len(pcm)} samples at {rate} Hz")
        out.append(f"constexpr size_t k{name}Samples = {len(pcm)};")
        out.append(f"constexpr uint32_t k{name}RateHz = {rate};")
        out.append(f"constexpr bool k{name}HasBaseline = {'true' if baseline is not None else 'false'};")
        out.append(f"constexpr float k{name}Baseline = {baseline if baseline is not None else 0.0}f;")
        out.append(f"const int32_t k{name}Pcm[k{name}Samples] = {{")
        for i in range(0, len(pcm), 16):
            out.append("    " + ", ".join(str(v) for v in pcm[i:i + 16]) + ",")
        out.append("};")
        out.append("")
    with open(args.out, "w", newline="\n") as f:
        f.write("\n".join(out))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
